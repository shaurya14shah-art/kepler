"""Generate THIRD_PARTY_NOTICES.md: every open-source component Kepler ships or uses, with its licence.

Run from the repo root with the project's environment:  backend/.venv/bin/python scripts/third_party_notices.py
(`make notices` does this). It reads the installed Python packages (runtime dependencies of kepler-watchdog, walked
recursively) and the dashboard's production npm packages, so the list always matches what's actually shipped.
"""
import json
import re
import subprocess
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = [ROOT / "THIRD_PARTY_NOTICES.md", ROOT / "backend" / "THIRD_PARTY_NOTICES.md"]


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _licence(dist) -> str:
    md = dist.metadata
    expr = md.get("License-Expression")
    if expr:
        return expr
    classifiers = [c.split("::")[-1].strip() for c in md.get_all("Classifier") or [] if c.startswith("License ::")]
    if classifiers:
        return ", ".join(dict.fromkeys(classifiers))
    lic = (md.get("License") or "").strip()
    return lic.splitlines()[0][:80] if lic else "see the package"


def python_packages() -> list[tuple[str, str, str]]:
    seen, todo, out = set(), ["kepler-watchdog"], []
    while todo:
        name = _norm(todo.pop())
        if name in seen:
            continue
        seen.add(name)
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            continue
        for req in dist.requires or []:
            if "extra ==" in req:  # optional extras aren't shipped
                continue
            todo.append(re.split(r"[ ;<>=!~\[(]", req, maxsplit=1)[0])
        if name != "kepler-watchdog":
            out.append((dist.metadata["Name"], dist.version, _licence(dist)))
    return sorted(out, key=lambda r: r[0].lower())


def npm_packages() -> list[tuple[str, str, str]]:
    try:
        tree = json.loads(subprocess.run(["npm", "ls", "--omit=dev", "--all", "--json"], cwd=ROOT / "frontend",
                                         capture_output=True, text=True, check=False).stdout or "{}")
    except (OSError, ValueError):
        return []
    found = {}

    def walk(deps):
        for name, info in (deps or {}).items():
            key = (name, info.get("version", "?"))
            if key not in found:
                pj = ROOT / "frontend" / "node_modules" / name / "package.json"
                lic = "?"
                try:
                    lic = json.loads(pj.read_text()).get("license") or "?"
                except (OSError, ValueError):
                    pass
                found[key] = lic if isinstance(lic, str) else json.dumps(lic)
            walk(info.get("dependencies"))
    walk(tree.get("dependencies"))
    return sorted(((n, v, lic) for (n, v), lic in found.items()), key=lambda r: r[0].lower())


def main() -> None:
    py, js = python_packages(), npm_packages()
    lines = [
        "# Third-party notices",
        "",
        "Kepler is proprietary software (see LICENSE). It is built on the open-source components below, each under its",
        "own licence; their copyright notices and licence texts ship inside each package. This file is generated by",
        "`scripts/third_party_notices.py` (`make notices`) from what is actually installed and bundled.",
        "",
        f"## Python packages ({len(py)})",
        "",
        "| package | version | licence |",
        "|---|---|---|",
        *[f"| {n} | {v} | {lic} |" for n, v, lic in py],
        "",
        f"## Dashboard (bundled JavaScript, {len(js)})",
        "",
        "| package | version | licence |",
        "|---|---|---|",
        *[f"| {n} | {v} | {lic} |" for n, v, lic in js],
        "",
        "## Data and tools that are not bundled",
        "",
        "These are downloaded or installed by the user, on request, and keep their own licences:",
        "",
        "- **Simple English Wikipedia** (`kepler learn wikipedia`) and live Wikipedia lookups: text under CC BY-SA 4.0,",
        "  by Wikipedia contributors. Kepler shows the source article and licence with every answer drawn from it.",
        "- **Open English WordNet** (`kepler learn wordnet`): CC BY 4.0.",
        "- **Tectonic** (optional LaTeX engine for `kepler write`): MIT licence, installed separately.",
        "- **Razorpay Checkout** (only if billing is ever enabled): loaded from Razorpay's servers under Razorpay's terms.",
        "",
    ]
    text = "\n".join(lines)
    for path in OUT:
        path.write_text(text)
    print(f"wrote {OUT[0].name}: {len(py)} Python + {len(js)} JavaScript packages")


if __name__ == "__main__":
    main()
